/** 循环基础样本生成只读凭证分录矩阵（用于 Story 大量行列展示） */
export function buildVoucherQueryMatrix(rowCount: number): VoucherStringCell[][] {
  const rows: VoucherStringCell[][] = [];
  const base = VOUCHER_TEMPLATE_ROWS;
  for (let i = 0; i < rowCount; i++) {
    const src = base[i % base.length];
    const row: VoucherStringCell[] = src.map((cell) => ({ value: cell, readOnly: true }));
    rows.push(row);
  }
  return rows;
}
